"""
SilentGPT — Document & Presentation Generator
Zero Data Retention: files are created in memory and never saved to disk.
"""

import io
from docx import Document
from docx.shared import Pt, Inches, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
from pptx import Presentation
from pptx.util import Inches, Pt
from pptx.dml.color import RGBColor as PptRGB
from pptx.enum.text import PP_ALIGN


def create_document(title: str, sections: list[dict]) -> bytes:
    """
    Create a Word document in memory.
    sections = [{"heading": "...", "content": "..."}, ...]
    Returns: .docx file as bytes
    """
    doc = Document()

    # Title
    title_para = doc.add_heading(title, level=0)
    title_para.alignment = WD_ALIGN_PARAGRAPH.CENTER

    for section in sections:
        doc.add_heading(section.get("heading", "Section"), level=1)
        para = doc.add_paragraph(section.get("content", ""))
        para.paragraph_format.space_after = Pt(12)

    # Save to memory (no disk write)
    buffer = io.BytesIO()
    doc.save(buffer)
    buffer.seek(0)
    return buffer.getvalue()


def create_presentation(title: str, slides_data: list[dict]) -> bytes:
    """
    Create a PowerPoint presentation in memory.
    slides_data = [{"title": "...", "points": ["...", "..."]}, ...]
    Returns: .pptx file as bytes
    """
    prs = Presentation()
    prs.slide_width = Inches(13.333)
    prs.slide_height = Inches(7.5)

    # Title slide
    title_slide_layout = prs.slide_layouts[0]
    slide = prs.slides.add_slide(title_slide_layout)
    slide.shapes.title.text = title
    if slide.placeholders[1]:
        slide.placeholders[1].text = "Generated by SilentGPT • Zero Data Retention"

    # Content slides
    bullet_layout = prs.slide_layouts[1]
    for slide_info in slides_data:
        slide = prs.slides.add_slide(bullet_layout)
        slide.shapes.title.text = slide_info.get("title", "Slide")

        body = slide.shapes.placeholders[1].text_frame
        body.clear()

        points = slide_info.get("points", [])
        for i, point in enumerate(points):
            if i == 0:
                p = body.paragraphs[0]
            else:
                p = body.add_paragraph()
            p.text = point
            p.level = 0

    buffer = io.BytesIO()
    prs.save(buffer)
    buffer.seek(0)
    return buffer.getvalue()