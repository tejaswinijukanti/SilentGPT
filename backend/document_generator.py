"""
SilentGPT — Document & Presentation Generator
Zero Data Retention: files are created in memory and never saved to disk.
"""

import io
from docx import Document
from docx.shared import Pt as DocxPt
from docx.enum.text import WD_ALIGN_PARAGRAPH

from pptx import Presentation
from pptx.util import Inches, Pt, Emu
from pptx.dml.color import RGBColor
from pptx.enum.text import PP_ALIGN, MSO_ANCHOR
from pptx.oxml.ns import nsmap
from pptx.oxml import parse_xml


def create_document(title: str, sections: list[dict]) -> bytes:
    """
    Create a Word document in memory.
    sections = [{"heading": "...", "content": "..."}, ...]
    Returns: .docx file as bytes
    """
    doc = Document()

    # Title
    title_para = doc.add_heading(title, level=0)
    title_para.alignment = WD_ALIGN_PARAGRAPH.CENTER

    for section in sections:
        doc.add_heading(section.get("heading", "Section"), level=1)
        para = doc.add_paragraph(section.get("content", ""))
        para.paragraph_format.space_after = DocxPt(12)

    # Save to memory (no disk write)
    buffer = io.BytesIO()
    doc.save(buffer)
    buffer.seek(0)
    return buffer.getvalue()


def _set_run_font(run, size_pt, bold=False, color=(233, 213, 255)):
    run.font.size = Pt(size_pt)
    run.font.bold = bold
    run.font.color.rgb = RGBColor(*color)
    run.font.name = "Calibri"


def _add_bg(slide, prs, rgb=(15, 12, 28)):
    """Solid dark background."""
    fill = slide.shapes.add_shape(
        1,  # rectangle
        Inches(0), Inches(0),
        prs.slide_width, prs.slide_height
    )
    fill.fill.solid()
    fill.fill.fore_color.rgb = RGBColor(*rgb)
    fill.line.fill.background()
    # send to back
    spTree = slide.shapes._spTree
    sp = fill._element
    spTree.remove(sp)
    spTree.insert(2, sp)


def create_presentation(title: str, slides_data: list[dict]) -> bytes:
    prs = Presentation()
    prs.slide_width = Inches(13.333)
    prs.slide_height = Inches(7.5)

    blank = prs.slide_layouts[6]  # blank

    # ── Title slide ──
    slide = prs.slides.add_slide(blank)
    _add_bg(slide, prs)

    # Purple accent bar at top
    bar = slide.shapes.add_shape(1, Inches(0), Inches(0), prs.slide_width, Inches(0.12))
    bar.fill.solid()
    bar.fill.fore_color.rgb = RGBColor(139, 92, 246)
    bar.line.fill.background()

    box = slide.shapes.add_textbox(Inches(0.8), Inches(2.4), Inches(11.7), Inches(2))
    tf = box.text_frame
    tf.word_wrap = True
    p = tf.paragraphs[0]
    p.alignment = PP_ALIGN.LEFT
    run = p.add_run()
    run.text = title
    _set_run_font(run, 36, bold=True, color=(245, 240, 255))

    sub = slide.shapes.add_textbox(Inches(0.8), Inches(4.5), Inches(11.7), Inches(1))
    sp = sub.text_frame.paragraphs[0]
    sr = sp.add_run()
    sr.text = "Generated by SilentGPT  ·  Zero Data Retention"
    _set_run_font(sr, 14, bold=False, color=(167, 139, 250))

    # ── Content slides ──
    for slide_info in slides_data:
        slide = prs.slides.add_slide(blank)
        _add_bg(slide, prs)

        # Top accent
        bar = slide.shapes.add_shape(1, Inches(0), Inches(0), prs.slide_width, Inches(0.08))
        bar.fill.solid()
        bar.fill.fore_color.rgb = RGBColor(139, 92, 246)
        bar.line.fill.background()

        # Title
        tbox = slide.shapes.add_textbox(Inches(0.7), Inches(0.35), Inches(12), Inches(1))
        tp = tbox.text_frame.paragraphs[0]
        tr = tp.add_run()
        tr.text = slide_info.get("title", "Slide")
        _set_run_font(tr, 26, bold=True, color=(245, 240, 255))

        # Accent line under title
        line = slide.shapes.add_shape(1, Inches(0.7), Inches(1.15), Inches(2.2), Inches(0.05))
        line.fill.solid()
        line.fill.fore_color.rgb = RGBColor(139, 92, 246)
        line.line.fill.background()

        # Bullets
        body = slide.shapes.add_textbox(Inches(0.7), Inches(1.5), Inches(12), Inches(5.2))
        tf = body.text_frame
        tf.word_wrap = True

        points = slide_info.get("points", [])[:6]  # max 6 bullets
        for i, point in enumerate(points):
            p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
            p.level = 0
            p.space_after = Pt(14)
            run = p.add_run()
            run.text = f"•  {point}"
            _set_run_font(run, 18, bold=False, color=(220, 210, 245))

        # Footer
        foot = slide.shapes.add_textbox(Inches(0.7), Inches(7.0), Inches(12), Inches(0.35))
        fp = foot.text_frame.paragraphs[0]
        fr = fp.add_run()
        fr.text = "SilentGPT"
        _set_run_font(fr, 11, bold=False, color=(120, 100, 160))

    buffer = io.BytesIO()
    prs.save(buffer)
    buffer.seek(0)
    return buffer.getvalue()